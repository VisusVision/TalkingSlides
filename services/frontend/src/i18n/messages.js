export function translateAppMessage(locale, key, params = {}) {
  const template = APP_MESSAGES[locale]?.[key] ?? APP_MESSAGES.en[key] ?? key;
  return String(template).replace(/\{\{\s*(\w+)\s*\}\}/g, (_, name) => (
    Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : ''
  ));
}
