export function studioWorkspaceLocale(rawLocale = '') {
  const baseLocale = String(rawLocale || '').trim().toLowerCase().split(/[-_]/)[0];
  return Object.prototype.hasOwnProperty.call(STUDIO_WORKSPACE_MESSAGES, baseLocale) ? baseLocale : 'en';
}

export function studioWorkspaceCopy(rawLocale = '') {
  const locale = studioWorkspaceLocale(rawLocale);
  return {
    ...STUDIO_WORKSPACE_MESSAGES.en,
    ...STUDIO_INSPECTOR_MESSAGES.en,
    ...STUDIO_EXPERIENCE_MESSAGES.en,
    ...STUDIO_FIRST_RUN_MESSAGES.en,
    ...STUDIO_GUIDANCE_MESSAGES.en,
    ...STUDIO_WORKSPACE_MESSAGES[locale],
    ...STUDIO_INSPECTOR_MESSAGES[locale],
    ...STUDIO_EXPERIENCE_MESSAGES[locale],
    ...STUDIO_FIRST_RUN_MESSAGES[locale],
    ...STUDIO_GUIDANCE_MESSAGES[locale],
  };
}
